CREATE TABLE businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    address VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    name VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    name VARCHAR(160) NOT NULL,
    sku VARCHAR(60),
    barcode VARCHAR(60),
    category VARCHAR(80),
    unit VARCHAR(30),
    purchase_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    stock_qty INT NOT NULL DEFAULT 0,
    low_stock_threshold INT NOT NULL DEFAULT 5,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_products_business ON products (business_id);

CREATE TABLE parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    type VARCHAR(20) NOT NULL,
    name VARCHAR(160) NOT NULL,
    phone VARCHAR(30),
    address VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_parties_business_type ON parties (business_id, type);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    invoice_no VARCHAR(40) NOT NULL,
    customer_id BIGINT REFERENCES parties (id),
    sale_date DATE NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL,
    discount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total NUMERIC(14, 2) NOT NULL,
    paid NUMERIC(14, 2) NOT NULL DEFAULT 0,
    note VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_sales_invoice UNIQUE (business_id, invoice_no)
);
CREATE INDEX idx_sales_business_date ON sales (business_id, sale_date);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id),
    product_name VARCHAR(160) NOT NULL,
    qty INT NOT NULL,
    unit_price NUMERIC(14, 2) NOT NULL,
    cost_price NUMERIC(14, 2) NOT NULL,
    line_total NUMERIC(14, 2) NOT NULL
);

CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    bill_no VARCHAR(40) NOT NULL,
    supplier_id BIGINT REFERENCES parties (id),
    purchase_date DATE NOT NULL,
    total NUMERIC(14, 2) NOT NULL,
    paid NUMERIC(14, 2) NOT NULL DEFAULT 0,
    note VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_purchases_bill UNIQUE (business_id, bill_no)
);
CREATE INDEX idx_purchases_business_date ON purchases (business_id, purchase_date);

CREATE TABLE purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchases (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id),
    product_name VARCHAR(160) NOT NULL,
    qty INT NOT NULL,
    unit_cost NUMERIC(14, 2) NOT NULL,
    line_total NUMERIC(14, 2) NOT NULL
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    ref_type VARCHAR(20) NOT NULL,
    ref_id BIGINT NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    method VARCHAR(30),
    paid_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_payments_ref ON payments (business_id, ref_type, ref_id);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    title VARCHAR(160) NOT NULL,
    category VARCHAR(80),
    amount NUMERIC(14, 2) NOT NULL,
    expense_date DATE NOT NULL,
    note VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_expenses_business_date ON expenses (business_id, expense_date);
